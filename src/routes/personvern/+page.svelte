    <section>
      <h2>5. Hvor lenge lagrer vi opplysningene?</h2>
      <p>Konto- og profilopplysninger lagres normalt så lenge kontoen eksisterer. Du kan slette kontoen fra innstillingene. Da slettes kontoen, følgerelasjoner, innlegg og opplastede medier fra den aktive tjenesten.</p>
      <p>Innlegg har i tillegg en lagringsperiode knyttet til planen din. Gratisplanen beholder for tiden innlegg i opptil 12 måneder, mens Person-planen kan beholde dem i opptil 5 år.</p>
      <p>Innloggingsøkter utløper normalt etter 30 dager. Lokale produksjonsbackuper beholdes normalt i 14 dager, slik at slettede opplysninger kan finnes i sikkerhetskopier i en begrenset periode før de roteres ut.</p>
      <p>Opplysninger som må oppbevares lenger på grunn av lovpålagte krav, tvister eller nødvendige sikkerhetsformål kan beholdes så lenge det konkrete formålet eller lovkravet krever det.</p>
