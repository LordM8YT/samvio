      <h2>2. Hvilke opplysninger behandler vi?</h2>
      <p><strong>Vipps Logg inn:</strong> Når du oppretter konto eller logger inn, ber Samvio om navn, verifisert e-postadresse og fødselsdato fra Vipps, samt en stabil Vipps-brukeridentifikator. Vipps viser deg hvilke opplysninger som deles før du godkjenner. Fødselsdato brukes blant annet til å kontrollere aldersgrensen og plassere kontoen i riktig aldersgruppe.</p>
      <p>Vipps opplyser at navn og fødselsdato er verifisert mot Folkeregisteret og at e-postadressen er verifisert. Vipps Logg inn er likevel ikke BankID eller en sertifisert elektronisk ID.</p>
      <p><strong>Konto og profil:</strong> Vi lagrer blant annet e-postadresse, navn, brukernavn, profiltekst, profil- og forsidebilde, profilinnstillinger, kontostatus og nødvendig informasjon om innlogging og økter. Vipps-kontoer har ikke et Samvio-passord lagret.</p>
      <p><strong>Innhold og aktivitet:</strong> Innlegg, bilder og videoer, kommentarer, reaksjoner, følgerelasjoner, blokkeringer, varsler, rapporter til moderering og valgte personvern- og varslingsinnstillinger lagres når du bruker funksjonene.</p>
      <p><strong>Abonnement og betaling:</strong> Ved et betalt abonnement lagrer Samvio nødvendige avtale- og betalingsreferanser, abonnementstype, pris, status, betalingsperiode og hendelser fra Vipps. Kort-, konto- og andre betalingsopplysninger behandles av Vipps MobilePay og lagres ikke av Samvio.</p>
      <p><strong>Drift og statistikk:</strong> Vi kan lagre kilde for hvordan du fant Samvio eller hvem som inviterte deg, og aggregert statistikk over besøk og registreringer. Dette brukes til å forstå om tjenesten blir funnet og brukt, ikke til målrettet reklame.</p>
    </section>

