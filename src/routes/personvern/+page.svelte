      <p>Vipps MobilePay er selv behandlingsansvarlig for sin behandling knyttet til Vipps Logg inn og betaling. Profilopplysninger du velger å gjøre synlige i Samvio kan også vises til andre brukere i samsvar med profil- og innholdsinnstillingene dine.</p>
      <p>Vi kan utlevere opplysninger til politi, domstoler eller andre offentlige myndigheter når vi er rettslig forpliktet til det, eller når annet gyldig rettslig grunnlag foreligger.</p>
