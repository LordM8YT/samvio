        <li>føre enkel, aggregert statistikk for drift og videreutvikling.</li>
      </ul>
      <p>Behandlingsgrunnlaget er hovedsakelig at behandlingen er nødvendig for å inngå eller oppfylle avtalen om Samvio. For sikkerhet, misbruksforebygging og forsvarlig drift kan vi støtte oss på en berettiget interesse etter en interesseavveining. Når loven krever at opplysninger behandles eller oppbevares, er behandlingsgrunnlaget en rettslig forpliktelse.</p>
      <p>Vipps innhenter ditt samtykke til å dele de forespurte profilopplysningene med Samvio. Etter at Samvio mottar opplysningene, er Samvio selv behandlingsansvarlig for den videre behandlingen.</p>
